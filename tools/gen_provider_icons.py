#!/usr/bin/env python3
"""从 LobeHub 单色 SVG 生成 Avalonia 路径数据（src/TKCode.Desktop/Icons/ProviderIconPaths.g.cs）。

单色图标转成 StreamGeometry 字符串，交给 AtomUI Icon 绘制，从而跟随前景色；
彩色图标（*-color.svg）保持 SVG，由 Svg 控件渲染。
用法：python3 -I tools/gen_provider_icons.py
"""
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SVG_DIR = ROOT / "src/TKCode.Desktop/Assets/ProviderIcons/svg"
OUT = ROOT / "src/TKCode.Desktop/Icons/ProviderIconPaths.g.cs"
NS = "{http://www.w3.org/2000/svg}"


def num(v: str) -> float:
    return float(v)


def shape_data(el) -> str | None:
    tag = el.tag.removeprefix(NS)
    if tag == "path":
        return el.get("d")
    if tag in ("circle", "ellipse"):
        cx, cy = num(el.get("cx", "0")), num(el.get("cy", "0"))
        rx = num(el.get("r") or el.get("rx"))
        ry = num(el.get("r") or el.get("ry"))
        return f"M{cx - rx:g},{cy:g}a{rx:g},{ry:g} 0 1,0 {2 * rx:g},0a{rx:g},{ry:g} 0 1,0 {-2 * rx:g},0z"
    if tag in ("title", "defs", "svg", "g"):
        return None
    raise ValueError(f"unsupported element <{tag}>")


def opacity(el) -> float:
    value = 1.0
    for attr in ("opacity", "fill-opacity"):
        if el.get(attr):
            value *= num(el.get(attr))
    return value


def convert(file: pathlib.Path):
    root = ET.parse(file).getroot()
    if root.get("viewBox") != "0 0 24 24":
        raise ValueError(f"{file.name}: unexpected viewBox {root.get('viewBox')}")
    evenodd = root.get("fill-rule") == "evenodd"
    parts = []
    for el in root.iter():
        if el is root:
            continue
        if el.get("transform"):
            raise ValueError(f"{file.name}: transform not supported")
        data = shape_data(el)
        if data:
            rule = el.get("fill-rule") or ("evenodd" if evenodd else "nonzero")
            prefix = "F0 " if rule == "evenodd" else "F1 "
            parts.append((prefix + re.sub(r"\s+", " ", data.strip()), opacity(el)))
    return parts


def main():
    mono = sorted(p for p in SVG_DIR.glob("*.svg") if not p.stem.endswith("-color"))
    colored = sorted(p.stem.removesuffix("-color") for p in SVG_DIR.glob("*-color.svg"))
    lines = [
        "// <auto-generated>由 tools/gen_provider_icons.py 从 Assets/ProviderIcons/svg 生成，请勿手改。</auto-generated>",
        "using System.Collections.Frozen;",
        "",
        "namespace TKCode.Desktop.Icons;",
        "",
        "internal static class ProviderIconPaths",
        "{",
        "    /// <summary>单色图标：每项为 (路径数据, 不透明度)；路径数据以 F0（EvenOdd）/ F1（NonZero）开头。</summary>",
        "    public static readonly FrozenDictionary<string, (string Data, double Opacity)[]> Mono =",
        "        new Dictionary<string, (string Data, double Opacity)[]>",
        "        {",
    ]
    for p in mono:
        items = ", ".join(f'("{d}", {o:g})' for d, o in convert(p))
        lines.append(f'            ["{p.stem}"] = [{items}],')
    lines += [
        "        }.ToFrozenDictionary();",
        "",
        "    /// <summary>有品牌彩色版本（Assets/ProviderIcons/svg/&lt;key&gt;-color.svg）的图标。</summary>",
        "    public static readonly FrozenSet<string> Colored = new[]",
        "    {",
        "        " + ", ".join(f'"{k}"' for k in colored) + ",",
        "    }.ToFrozenSet();",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(mono)} mono, {len(colored)} colored -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
